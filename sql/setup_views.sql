-- 12. V_VETERANS: Veteran status by county
------------------------------------------------------------
CREATE OR REPLACE VIEW V_VETERANS AS
WITH fips AS (
    SELECT DISTINCT STATE, STATE_FIPS, COUNTY_FIPS, COUNTY
    FROM US_OPEN_CENSUS_DATA_NEIGHBORHOOD_INSIGHTS_FREE_DATASET.PUBLIC."2020_METADATA_CBG_FIPS_CODES"
    WHERE STATE IS NOT NULL
),
vet AS (
    SELECT LEFT(CENSUS_BLOCK_GROUP, 2) AS STATE_FIPS, SUBSTR(CENSUS_BLOCK_GROUP, 3, 3) AS COUNTY_FIPS,
        "B21001e1" AS TOTAL_POP_18_PLUS, "B21001e2" AS VETERANS, "B21001e3" AS NONVETERANS
    FROM US_OPEN_CENSUS_DATA_NEIGHBORHOOD_INSIGHTS_FREE_DATASET.PUBLIC."2020_CBG_B21"
)
SELECT f.STATE AS STATE_NAME, f.STATE_FIPS, f.COUNTY, f.COUNTY_FIPS,
    SUM(v.TOTAL_POP_18_PLUS) AS TOTAL_POP_18_PLUS, SUM(v.VETERANS) AS VETERANS,
    SUM(v.NONVETERANS) AS NONVETERANS,
    ROUND(SUM(v.VETERANS) * 100.0 / NULLIF(SUM(v.TOTAL_POP_18_PLUS), 0), 1) AS VETERAN_RATE
FROM vet v
JOIN fips f ON v.STATE_FIPS = f.STATE_FIPS AND v.COUNTY_FIPS = f.COUNTY_FIPS
GROUP BY f.STATE, f.STATE_FIPS, f.COUNTY, f.COUNTY_FIPS;

