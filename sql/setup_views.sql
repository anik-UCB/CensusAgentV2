JOIN fips f ON s.STATE_FIPS = f.STATE_FIPS AND s.COUNTY_FIPS = f.COUNTY_FIPS
GROUP BY f.STATE, f.STATE_FIPS, f.COUNTY, f.COUNTY_FIPS;

