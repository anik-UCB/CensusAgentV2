-- 8. V_HEALTH_INSURANCE: Coverage by county
------------------------------------------------------------
CREATE OR REPLACE VIEW V_HEALTH_INSURANCE AS
WITH fips AS (
    SELECT DISTINCT STATE, STATE_FIPS, COUNTY_FIPS, COUNTY
    FROM US_OPEN_CENSUS_DATA_NEIGHBORHOOD_INSIGHTS_FREE_DATASET.PUBLIC."2020_METADATA_CBG_FIPS_CODES"
    WHERE STATE IS NOT NULL
),
ins AS (
    SELECT LEFT(CENSUS_BLOCK_GROUP, 2) AS STATE_FIPS, SUBSTR(CENSUS_BLOCK_GROUP, 3, 3) AS COUNTY_FIPS,
        "B27010e1" AS TOTAL_POP,
        "B27010e17" AS UNINSURED_UNDER_19, "B27010e33" AS UNINSURED_19_TO_34,
        "B27010e50" AS UNINSURED_35_TO_64, "B27010e66" AS UNINSURED_65_PLUS
    FROM US_OPEN_CENSUS_DATA_NEIGHBORHOOD_INSIGHTS_FREE_DATASET.PUBLIC."2020_CBG_B27"
)
SELECT f.STATE AS STATE_NAME, f.STATE_FIPS, f.COUNTY, f.COUNTY_FIPS,
    SUM(i.TOTAL_POP) AS TOTAL_POP,
    SUM(i.UNINSURED_UNDER_19)+SUM(i.UNINSURED_19_TO_34)+SUM(i.UNINSURED_35_TO_64)+SUM(i.UNINSURED_65_PLUS) AS TOTAL_UNINSURED,
    SUM(i.TOTAL_POP)-(SUM(i.UNINSURED_UNDER_19)+SUM(i.UNINSURED_19_TO_34)+SUM(i.UNINSURED_35_TO_64)+SUM(i.UNINSURED_65_PLUS)) AS TOTAL_INSURED,
    ROUND((SUM(i.UNINSURED_UNDER_19)+SUM(i.UNINSURED_19_TO_34)+SUM(i.UNINSURED_35_TO_64)+SUM(i.UNINSURED_65_PLUS)) * 100.0 / NULLIF(SUM(i.TOTAL_POP), 0), 1) AS UNINSURED_RATE
FROM ins i
JOIN fips f ON i.STATE_FIPS = f.STATE_FIPS AND i.COUNTY_FIPS = f.COUNTY_FIPS
GROUP BY f.STATE, f.STATE_FIPS, f.COUNTY, f.COUNTY_FIPS;

