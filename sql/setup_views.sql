-- 13. V_SNAP: Food stamp receipt by county
------------------------------------------------------------
CREATE OR REPLACE VIEW V_SNAP AS
WITH fips AS (
    SELECT DISTINCT STATE, STATE_FIPS, COUNTY_FIPS, COUNTY
    FROM US_OPEN_CENSUS_DATA_NEIGHBORHOOD_INSIGHTS_FREE_DATASET.PUBLIC."2020_METADATA_CBG_FIPS_CODES"
    WHERE STATE IS NOT NULL
),
snap AS (
    SELECT LEFT(CENSUS_BLOCK_GROUP, 2) AS STATE_FIPS, SUBSTR(CENSUS_BLOCK_GROUP, 3, 3) AS COUNTY_FIPS,
        "B22010e1" AS TOTAL_HOUSEHOLDS, "B22010e2" AS RECEIVED_SNAP, "B22010e5" AS DID_NOT_RECEIVE_SNAP
    FROM US_OPEN_CENSUS_DATA_NEIGHBORHOOD_INSIGHTS_FREE_DATASET.PUBLIC."2020_CBG_B22"
)
SELECT f.STATE AS STATE_NAME, f.STATE_FIPS, f.COUNTY, f.COUNTY_FIPS,
    SUM(s.TOTAL_HOUSEHOLDS) AS TOTAL_HOUSEHOLDS, SUM(s.RECEIVED_SNAP) AS RECEIVED_SNAP,
