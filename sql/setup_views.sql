-- Complete setup script for all 26 Census views (county-level + state-level)
-- Co-authored with CoCo

-- Prerequisites:
-- 1. SafeGraph US Open Census Data marketplace listing installed
-- 2. Run as ACCOUNTADMIN or role with CREATE DATABASE/VIEW privileges
-- NOTE: Source table columns are mixed-case and must be double-quoted.

CREATE DATABASE IF NOT EXISTS CENSUS_AGENT;
USE DATABASE CENSUS_AGENT;
CREATE SCHEMA IF NOT EXISTS PUBLIC;
USE SCHEMA PUBLIC;

